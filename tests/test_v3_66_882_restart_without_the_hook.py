def test_the_tool_reads_a_real_state_file(tmp_path):
    state = tmp_path / "boot_state"
    state.write_text("definitely-not-this-machines-boot-id\n2026-01-01T00:00:00Z\nstartup\n")
    r = _run(state)
    assert r.returncode == 1, (r.returncode, r.stdout, r.stderr)
    assert json.loads(r.stdout)["status"] == "restarted"


def test_an_absent_state_file_exits_two(tmp_path):
    r = _run(tmp_path / "nope")
    assert r.returncode == 2, (r.returncode, r.stdout)
    assert json.loads(r.stdout)["status"] == "unevaluable"


def test_an_empty_state_file_is_unevaluable_not_ok(tmp_path):
    """A truncated write must not read as agreement. The hook writes this file
    with a plain redirect, so a killed process can leave it empty."""
    state = tmp_path / "boot_state"
    state.write_text("")
    r = _run(state)
    assert r.returncode == 2, (r.returncode, r.stdout)


def test_the_selftest_passes():
    r = subprocess.run([sys.executable, str(TOOL), "--selftest"],
                       capture_output=True, text=True, timeout=60)
    assert r.returncode == 0, r.stdout + r.stderr
    assert "SELFTEST PASS" in r.stdout


