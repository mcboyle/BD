def test_the_hook_records_the_boot_id(tmp_path):
    """Otherwise the tool grades a file nobody writes and always says UNKNOWN --
    a gate that cannot see its subject, in the pair built to avoid one."""
    from test_v3_66_879_provision_trigger_sees_its_subject import (
        _origin_and_clone,
    )
    _origin, clone = _origin_and_clone(tmp_path)
    fake_home = tmp_path / "home"
    fake_home.mkdir()
    env = dict(os.environ)
    env["CLAUDE_CODE_REMOTE"] = "true"
    env["CLAUDE_PROJECT_DIR"] = str(clone)
    env["HOME"] = str(fake_home)
    env.pop("CLAUDE_ENV_FILE", None)
    subprocess.run(["bash", str(HOOK)], cwd=str(clone),
                   input='{"source":"startup"}', capture_output=True,
                   text=True, timeout=300, env=env)
    state = fake_home / ".bd_boot_state"
    assert state.exists(), (
        "the hook did not write the boot record, so bd-restart-check can only "
        "ever return UNEVALUABLE")
    lines = state.read_text().splitlines()
    assert len(lines) >= 3, "the record is missing fields: %r" % lines
    assert lines[2] == "startup", (
        "the record does not carry the hook source, so a reader cannot tell "
        "which event last ran it: %r" % lines)


def test_the_hook_writing_the_record_cannot_break_the_repair(tmp_path):
    """The record is written last and never gated on. A failure there must not
    cost the repair, which is the part that matters."""
    from test_v3_66_879_provision_trigger_sees_its_subject import (
        _head, _origin_and_clone, _tip,
    )
    _origin, clone = _origin_and_clone(tmp_path)
    env = dict(os.environ)
    env["CLAUDE_CODE_REMOTE"] = "true"
    env["CLAUDE_PROJECT_DIR"] = str(clone)
    env["HOME"] = "/nonexistent-home-that-cannot-be-written"
    env.pop("CLAUDE_ENV_FILE", None)
    r = subprocess.run(["bash", str(HOOK)], cwd=str(clone),
                       input='{"source":"startup"}', capture_output=True,
                       text=True, timeout=300, env=env)
    assert _head(clone) == _tip(clone), (
        "an unwritable boot-state path prevented the rollback repair. "
        "stderr=%r" % r.stderr)
    assert r.returncode == 0, r.stderr
