def test_derived_16k_tag_on_overflow_is_parity(run):
    """Positive control: the probe CAN say yes -- same weights (Linux path) and num_ctx 16384."""
    rc, out = run(PRIMARY, _show("qwen2.5-coder:7b-16k", LINUX_BLOB + WEIGHTS, "16384", "qwen2.5-coder:7b-instruct-q4_K_M"))
    assert (rc, out) == (0, "PARITY num_ctx=16384 weights=" + WEIGHTS[:12])


