"""O1698 c4b-context-parity: the C4 overflow backend must serve local-coder with .137's context, not Ollama's default.

.137 serves local-coder as qwen2.5-coder:7b-16k (num_ctx 16384, same weights as qwen2.5-coder:7b); the C4 serve script
pulled the base tag only, so overflow would truncate prompts the primary accepts. The candidate (harness-work FIX dir,
opt-in via BD_O1698_C4B_CONTEXT_PARITY_CANDIDATE) has bd-c4-context-parity.sh (PARITY | MISMATCH:<field> | COULD-NOT-LOOK,
never PARITY on what it can't judge), Modelfile.local-coder-16k and PATCH-serve.diff for bd-c4-cpu-serve.sh.

Fixtures are the real .137 /api/show bodies (captured read-only 2026-10-03, Ollama 0.34.0, Windows blob paths), trimmed
to the fields the tool reads; the full captures are re-checked when the candidate's evidence/captures dir is present.
"""
