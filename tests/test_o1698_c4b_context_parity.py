SERVE_BASE = os.environ.get("BD_O1698_C4B_SERVE_BASE", "")
SERVE_BASE_SHA = "d10317d66375b79b9d9daf840ae04a88e541e63d8209a8a7d34152d98579734b"   # C4d r2 serve.sh (PM 18:52Z; C4d r1 8f20238d superseded)
pytestmark = pytest.mark.skipif(not CANDIDATE, reason="candidate opt-in required")

WEIGHTS = "60e05f2100071479f596b964f89f510f057ce397ea22f2833a0cfe029bfc2463"
OTHER = "f" * 64
WIN_BLOB = "C:\\Users\\Administrator\\.ollama\\models\\blobs\\sha256-"
LINUX_BLOB = "/home/bd/.local/share/bd-c4/models/blobs/sha256-"


def _show(tag, blob=WIN_BLOB + WEIGHTS, num_ctx="16384", parent="qwen2.5-coder:7b"):
    """A /api/show body shaped like .137's: generated-modelfile header (its '# FROM <tag>' is a comment), FROM blob."""
    body = {"modelfile": ('# Modelfile generated by "ollama show"\n'
                          "# To build a new Modelfile based on this, replace FROM with:\n"
                          f"# FROM {tag}\n\nFROM {blob}\nTEMPLATE \"\"\"{{{{ .Prompt }}}}\"\"\"\n"),
            "details": {"parent_model": parent, "format": "gguf", "family": "qwen2", "quantization_level": "Q4_K_M"}}
    if num_ctx is not None:
        body["parameters"] = f"num_ctx                        {num_ctx}"
        body["modelfile"] += f"PARAMETER num_ctx {num_ctx}\n"
    return body


@pytest.fixture
def run(tmp_path):
    tool = Path(CANDIDATE) / "bd-c4-context-parity.sh"
    assert tool.is_file() and os.access(tool, os.X_OK), tool

    def go(primary, overflow, *extra):
        args = [str(tool)]
        for side, body in (("primary", primary), ("overflow", overflow)):
            if body is not None:
                f = tmp_path / f"{side}.json"
                f.write_text(body if isinstance(body, str) else json.dumps(body))
                args += [f"--{side}-json", str(f)]
        r = subprocess.run(args + list(extra), capture_output=True, text=True, timeout=60)
        return r.returncode, r.stdout.strip()
    return go


PRIMARY = _show("qwen2.5-coder:7b-16k")


# ---- RED / GREEN / positive control -----------------------------------------------------------------------------------
def test_base_tag_on_overflow_is_a_num_ctx_mismatch(run):
    """Today's .120 serve set: the base tag, no PARAMETER num_ctx -> Ollama's default context."""
    rc, out = run(PRIMARY, _show("qwen2.5-coder:7b-instruct-q4_K_M", LINUX_BLOB + WEIGHTS, None, ""))
    assert (rc, out.split()[0]) == (1, "MISMATCH:num_ctx"), out
