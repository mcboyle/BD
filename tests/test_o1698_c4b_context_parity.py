# ---- the Modelfile and the serve-script diff --------------------------------------------------------------------------
def _modelfile_lines():
    text = (Path(CANDIDATE) / "Modelfile.local-coder-16k").read_text()
    return [line for line in text.splitlines() if line.strip() and not line.startswith("#")]


def test_modelfile_derives_16k_from_the_pulled_base_tag():
    assert _modelfile_lines() == ["FROM qwen2.5-coder:7b-instruct-q4_K_M", "PARAMETER num_ctx 16384"]


def _patched_render(tmp_path, model):
    base = Path(SERVE_BASE)
    assert hashlib.sha256(base.read_bytes()).hexdigest() == SERVE_BASE_SHA, "serve base drifted: rebase PATCH-serve.diff"
    work = tmp_path / "serve"
    work.mkdir()
    (work / base.name).write_bytes(base.read_bytes())
    patch = (Path(CANDIDATE) / "PATCH-serve.diff").read_text()
    subprocess.run(["patch", "-s", "-p1", "-d", str(work)], input=patch, text=True, check=True, timeout=30)
    (tmp_path / "place.tsv").write_text("10.0.70.120\tESXI01\n")
    (tmp_path / "census.tsv").write_text("host\tstatus\tidle_p95\tmem_available_bytes\n10.0.70.120\tFOUND\t32.0\t33930000000\n")
    r = subprocess.run(["bash", str(work / base.name), "10.0.70.120", "--model", model, "--placement", str(tmp_path / "place.tsv"),
                        "--census", str(tmp_path / "census.tsv"), "--ollama-tarball", "/nonexistent", "--ollama-sha256", "a" * 64,
                        "--expect-weights", WEIGHTS, "--render"], capture_output=True, text=True, timeout=60)
    assert r.returncode == 0, r.stderr
    subprocess.run(["bash", "-n"], input=r.stdout, text=True, check=True, timeout=30)
    return r.stdout


@pytest.mark.skipif(not SERVE_BASE, reason="BD_O1698_C4B_SERVE_BASE (the C4 serve script) not given")
def test_patched_serve_creates_checks_and_serves_the_16k_tag(tmp_path):
    out = _patched_render(tmp_path, "qwen2.5-coder:7b-q4")
    pull, create = out.index("ollama\" pull qwen2.5-coder:7b-instruct-q4_K_M"), out.index("create qwen2.5-coder:7b-16k")
    assert pull < out.index("C4_SERVE_WEIGHTS_MISMATCH") < create            # derive only from verified weights
    line = next(x for x in out.splitlines() if "printf" in x and "Modelfile.local-coder-16k" in x)
    written = line.split("printf '", 1)[1].split("'", 1)[0].replace("%s", "qwen2.5-coder:7b-instruct-q4_K_M")
    assert written.split("\\n")[:2] == _modelfile_lines()                    # the reviewed Modelfile, byte for byte
    assert f'[ "$ctx" != 16384 ] || [ "$derived" != "{WEIGHTS}" ]' in out and "C4_SERVE_CONTEXT_MISMATCH" in out
    assert "model=qwen2.5-coder:7b-16k base=qwen2.5-coder:7b-instruct-q4_K_M" in out


@pytest.mark.skipif(not SERVE_BASE, reason="BD_O1698_C4B_SERVE_BASE (the C4 serve script) not given")
def test_patched_serve_leaves_bge_m3_untouched(tmp_path):
    out = _patched_render(tmp_path, "bge-m3")
    assert '[ "bge-m3:latest" != "bge-m3:latest" ]' in out and "model=bge-m3:latest base=bge-m3:latest" in out
