import * as React from "react";

import { cn } from "@/lib/utils";

// Card is the workhorse mockup primitive. Per UI_TOKENS.md:
//   - hairline (0.5px) border, NOT 1px — signature visual
//   - no box-shadow, hairline + tinted background does separation
//   - rounded-lg (18px) for cards/sheets/hero containers
const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "hairline rounded-lg bg-surface text-ink",
      className,
    )}
    {...props}
  />
));
Card.displayName = "Card";

